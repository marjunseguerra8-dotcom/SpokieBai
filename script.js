let currentIndex = 0;
let isPlaying = false;
let isShuffle = false;



// DISPLAY SONGS
function displaySongs(list = songs) {
    musicGrid.innerHTML = "";

    list.forEach(song => {
        const index = songs.indexOf(song);

        const card = document.createElement("div");
        card.className = "music-card";

        card.innerHTML = `
            <img src="${song.cover}" alt="${song.title}">
            <h3>${song.title}</h3>
            <p>${song.artist}</p>
            <button class="card-play">
                <i class="fa-solid fa-play"></i>
            </button>
        `;

        card.addEventListener("click", () => playSong(index));

        musicGrid.appendChild(card);
    });
}

displaySongs();


// PLAY SONG
function playSong(index) {
    currentIndex = index;

    const song = songs[currentIndex];

    audio.src = song.audio;

    document.getElementById("currentTitle").textContent = song.title;
    document.getElementById("currentArtist").textContent = song.artist;
    document.getElementById("currentCover").src = song.cover;

    document.getElementById("lyricsTitle").textContent = song.title;
    document.getElementById("lyricsArtist").textContent = song.artist;
    document.getElementById("lyricsCover").src = song.cover;

    audio.play()
        .then(() => {
            isPlaying = true;
            updatePlayButton();
        })
        .catch(error => {
            console.error("Audio playback error:", error);
            isPlaying = false;
            updatePlayButton();
        });

    updateLyrics();
}


// PLAY / PAUSE
function updatePlayButton() {
    playBtn.innerHTML = isPlaying
        ? '<i class="fa-solid fa-pause"></i>'
        : '<i class="fa-solid fa-play"></i>';
}

playBtn.addEventListener("click", () => {
    if (!audio.src) {
        playSong(currentIndex);
        return;
    }

    if (audio.paused) {
        audio.play().then(() => {
            isPlaying = true;
            updatePlayButton();
        }).catch(() => {});
    } else {
        audio.pause();
        isPlaying = false;
        updatePlayButton();
    }
});

audio.addEventListener("play", () => {
    isPlaying = true;
    updatePlayButton();
});

audio.addEventListener("pause", () => {
    isPlaying = false;
    updatePlayButton();
});


// NEXT SONG
function nextSong() {
    if (isShuffle) {
        let next;

        do {
            next = Math.floor(Math.random() * songs.length);
        } while (next === currentIndex && songs.length > 1);

        playSong(next);
    } else {
        playSong((currentIndex + 1) % songs.length);
    }
}


// PREVIOUS SONG
function previousSong() {
    if (audio.currentTime > 3) {
        audio.currentTime = 0;
    } else {
        playSong((currentIndex - 1 + songs.length) % songs.length);
    }
}

document.getElementById("nextBtn").addEventListener("click", nextSong);
document.getElementById("prevBtn").addEventListener("click", previousSong);


