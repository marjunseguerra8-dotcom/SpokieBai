// REPEAT
const repeatBtn = document.getElementById("repeatBtn");

let repeatMode =1;
// 0 = Repeat Off
// 1 = Repeat All
// 2 = Repeat One


repeatBtn.addEventListener("click", () => {

    repeatMode = (repeatMode + 1) % 3;

    if (repeatMode === 0) {
        repeatBtn.style.color = "#888b86";
        repeatBtn.title = "Repeat Off";
        audio.loop = false;

    } else if (repeatMode === 1) {
        repeatBtn.style.color = "#179a1d";
        repeatBtn.title = "Repeat All";
        audio.loop = false;

    } else {
        repeatBtn.style.color = "#179a1d";
        repeatBtn.title = "Repeat One";
        audio.loop = true;
    }

    console.log("Repeat mode:", repeatBtn.title);
});

// SONG ENDED
audio.addEventListener("ended", () => {
    if (repeatMode === 2) {
        audio.currentTime = 0;
        audio.play();
    } else if (repeatMode === 1 || isShuffle) {
        nextSong();
    } else if (currentIndex < songs.length - 1) {
        playSong(currentIndex + 1);
    } else {
        isPlaying = false;
        updatePlayButton();
    }
});


// TIME FORMAT
function formatTime(seconds) {
    if (!Number.isFinite(seconds)) return "0:00";

    const minutes = Math.floor(seconds / 60);
    const remaining = Math.floor(seconds % 60);

    return `${minutes}:${String(remaining).padStart(2, "0")}`;
}


// AUDIO PROGRESS
audio.addEventListener("loadedmetadata", () => {
    document.getElementById("duration").textContent =
        formatTime(audio.duration);
});

audio.addEventListener("timeupdate", () => {
    if (!audio.duration) return;

    progress.value = (audio.currentTime / audio.duration) * 100;

    document.getElementById("currentTime").textContent =
        formatTime(audio.currentTime);

    updateLyrics();
});

progress.addEventListener("input", () => {
    if (audio.duration) {
        audio.currentTime =
            (progress.value / 100) * audio.duration;
    }
});


// VOLUME
volume.addEventListener("input", () => {
    audio.volume = Number(volume.value);
    audio.muted = false;
    updateVolumeIcon();
});

document.getElementById("muteBtn").addEventListener("click", () => {
    audio.muted = !audio.muted;
    updateVolumeIcon();
});

function updateVolumeIcon() {
    const icon = document.querySelector("#muteBtn i");

    if (audio.muted || audio.volume === 0) {
        icon.className = "fa-solid fa-volume-xmark";
    } else if (audio.volume < 0.5) {
        icon.className = "fa-solid fa-volume-low";
    } else {
        icon.className = "fa-solid fa-volume-high";
    }
}


// SEARCH
document.getElementById("search").addEventListener("input", event => {
    const query = event.target.value.toLowerCase();

    const filtered = songs.filter(song =>
        song.title.toLowerCase().includes(query) ||
        song.artist.toLowerCase().includes(query)
    );

    displaySongs(filtered);
});


// CATEGORY FILTER
document.querySelectorAll(".filter").forEach(button => {
    button.addEventListener("click", () => {
        document.querySelectorAll(".filter").forEach(btn =>
            btn.classList.remove("active")
        );

        button.classList.add("active");

        const category = button.dataset.filter.toLowerCase();

        const filtered = category === "all"
            ? songs
            : songs.filter(song => song.category === category);

        displaySongs(filtered);
    });
});


// TIMED LYRICS
function updateLyrics() {
    const song = songs[currentIndex];
    const lyricsText = document.getElementById("lyricsText");

    if (!song || !song.lyrics) return;

    const currentTime = audio.currentTime;

    let activeLyric = -1;

    song.lyrics.forEach((line, index) => {
        if (currentTime >= line.time) {
            activeLyric = index;
        }
    });

    lyricsText.innerHTML = "";

    song.lyrics.forEach((line, index) => {
        const paragraph = document.createElement("p");

        paragraph.textContent = line.text;

        if (index === activeLyric) {
            paragraph.classList.add("active-lyric");
        }

        lyricsText.appendChild(paragraph);
    });

    const activeElement = lyricsText.querySelector(".active-lyric");

    if (activeElement) {
        activeElement.scrollIntoView({
            behavior: "smooth",
            block: "center"
        });
    }
}


